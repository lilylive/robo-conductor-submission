"""Contact-driven KUKA pad performance. The original robo_conductor.py is untouched."""
from __future__ import annotations

import argparse
import json
import math
import os
import subprocess
import tempfile
import wave
from pathlib import Path

import imageio.v2 as imageio
import imageio_ffmpeg
import numpy as np
import pybullet as p
import pybullet_data

COLORS = ('red', 'blue', 'green')
PAD_POS = {'red': (0.48, -0.24, 0.055), 'blue': (0.54, 0.0, 0.055), 'green': (0.48, 0.24, 0.055)}
RGB = {'red': (0.78, 0.06, 0.05, 1), 'blue': (0.04, 0.15, 0.8, 1), 'green': (0.04, 0.6, 0.12, 1)}
GLOW = {'red': (1, 0.75, 0.6, 1), 'blue': (0.65, 0.85, 1, 1), 'green': (0.65, 1, 0.65, 1)}
# These are hand-authored, not LLM-generated.
PATTERNS = {
    'call': ['red', 'blue', 'green', 'red', 'blue', 'green', 'blue', 'red'],
    'pulse': ['red', 'red', 'blue', 'blue', 'green', 'green', 'blue', 'red'],
    'answer': ['green', 'blue', 'red', 'green', 'red', 'blue', 'green', 'red'],
}
HZ = 240
PAD_HALF = (0.085, 0.085, 0.012)


def validate_plan(plan):
    if not isinstance(plan, dict) or not isinstance(plan.get('sequence'), list) or not plan['sequence']:
        raise ValueError('Plan must be a JSON object containing a nonempty sequence list')
    if len(plan['sequence']) > 200 or any(c not in COLORS for c in plan['sequence']):
        raise ValueError('Sequence must contain at most 200 red, blue or green entries')
    return plan


def make_strikes(pattern, plan_file):
    if plan_file:
        path = Path(plan_file)
        plan = validate_plan(json.loads(path.read_text(encoding='utf-8')))
        return [{'color': c, 'pattern': 'external_plan'} for c in plan['sequence']], {
            'type': 'external_plan', 'file': str(path),
            'declared_source': plan.get('source', 'unspecified'),
            'instruction': plan.get('instruction'), 'model': plan.get('model'),
            'note': 'Source field is copied from the supplied file; it is not independently verified.'}
    names = list(PATTERNS) if pattern == 'all' else [pattern]
    return ([{'color': c, 'pattern': name} for name in names for c in PATTERNS[name]],
            {'type': 'manual', 'patterns': names, 'note': 'Sequences were hand-authored, not generated by AI.'})


def add_pad(client, color):
    col = p.createCollisionShape(p.GEOM_BOX, halfExtents=PAD_HALF, physicsClientId=client)
    vis = p.createVisualShape(p.GEOM_BOX, halfExtents=PAD_HALF, rgbaColor=RGB[color], physicsClientId=client)
    return p.createMultiBody(baseMass=0, baseCollisionShapeIndex=col, baseVisualShapeIndex=vis,
                             basePosition=PAD_POS[color], physicsClientId=client)


def image(width, height, client):
    view = p.computeViewMatrix(cameraEyePosition=[1.15, -1.05, 1.12],
                               cameraTargetPosition=[0.27, 0, 0.38], cameraUpVector=[0, 0, 1])
    projection = p.computeProjectionMatrixFOV(fov=57, aspect=width / height, nearVal=0.05, farVal=5)
    rgba = p.getCameraImage(width, height, viewMatrix=view, projectionMatrix=projection,
                            renderer=p.ER_TINY_RENDERER, physicsClientId=client)[2]
    return np.asarray(rgba, dtype=np.uint8).reshape(height, width, 4)[:, :, :3].copy()


def synthesize(events, duration, output, rate=48000):
    # Generated sine tones are an illustration triggered by detected contacts.
    samples = np.zeros(math.ceil(duration * rate), dtype=np.float64)
    notes = {'red': 261.63, 'blue': 329.63, 'green': 392.00}
    length = int(0.28 * rate)
    t = np.arange(length) / rate
    envelope = np.exp(-t * 14) * np.minimum(1, t * 180)
    for event in events:
        if not event['contact_confirmed']:
            continue
        start = round(event['contact_time_s'] * rate)
        end = min(len(samples), start + length)
        if start < end:
            tone = np.sin(2 * np.pi * notes[event['color']] * t[:end-start])
            samples[start:end] += 0.32 * tone * envelope[:end-start]
    pcm = (np.clip(samples, -0.95, 0.95) * 32767).astype('<i2')
    with wave.open(str(output), 'wb') as out:
        out.setnchannels(1)
        out.setsampwidth(2)
        out.setframerate(rate)
        out.writeframes(pcm.tobytes())


def run(strikes, provenance, output, log_path, audio_path, fps=30, width=960, height=540):
    if fps <= 0 or HZ % fps or fps > HZ:
        raise ValueError('fps must be a positive integer divisor of 240, e.g. 24 or 30')
    if width < 64 or height < 64 or width % 2 or height % 2:
        raise ValueError('width and height must be even integers >= 64')
    output, log_path, audio_path = map(Path, (output, log_path, audio_path))
    if output.suffix.lower() != '.mp4' or audio_path.suffix.lower() != '.wav':
        raise ValueError('video output must be .mp4 and audio output must be .wav')
    if len({output.resolve(), log_path.resolve(), audio_path.resolve()}) != 3:
        raise ValueError('video, log and audio output paths must be different')
    for path in (output, log_path, audio_path):
        path.parent.mkdir(parents=True, exist_ok=True)
    frame_steps = HZ // fps
    client = p.connect(p.DIRECT)
    if client < 0:
        raise RuntimeError('Could not connect to PyBullet')
    writer = None
    events = []
    collisions = []
    frame_count = 0
    step_count = 0
    glow_until = {color: -1 for color in COLORS}
    was_touching = {color: False for color in COLORS}
    active = None
    try:
        p.setAdditionalSearchPath(pybullet_data.getDataPath(), physicsClientId=client)
        p.setGravity(0, 0, -9.81, physicsClientId=client)
        p.setTimeStep(1 / HZ, physicsClientId=client)
        p.loadURDF('plane.urdf', physicsClientId=client)
        robot = p.loadURDF('kuka_iiwa/model.urdf', [0, 0, 0], useFixedBase=True, physicsClientId=client)
        pads = {c: add_pad(client, c) for c in COLORS}
        joints = [i for i in range(p.getNumJoints(robot, physicsClientId=client))
                  if p.getJointInfo(robot, i, physicsClientId=client)[2] == p.JOINT_REVOLUTE]
        if len(joints) != 7:
            raise RuntimeError('Unexpected KUKA joint layout')
        ee = 6
        home = [0.36, 0, 0.65]
        with tempfile.TemporaryDirectory(prefix='robo-conductor-') as tmp:
            silent = str(Path(tmp) / 'silent.mp4')
            writer = imageio.get_writer(silent, fps=fps, codec='libx264', quality=7, macro_block_size=1)

            def move(goal, seconds):
                nonlocal frame_count, step_count, active
                count = max(1, round(seconds * fps)) * frame_steps
                start = np.array(p.getLinkState(robot, ee, computeForwardKinematics=True,
                                                physicsClientId=client)[4])
                dest = np.array(goal)
                for n in range(count):
                    # A video frame describes the world at time step_count / 240.
                    if step_count % frame_steps == 0:
                        for color, body in pads.items():
                            p.changeVisualShape(body, -1,
                                rgbaColor=GLOW[color] if step_count < glow_until[color] else RGB[color],
                                physicsClientId=client)
                        writer.append_data(image(width, height, client))
                        frame_count += 1
                    f = (n + 1) / count
                    smooth = f * f * (3 - 2 * f)
                    target = (start * (1 - smooth) + dest * smooth).tolist()
                    qs = p.calculateInverseKinematics(robot, ee, target, maxNumIterations=100,
                                                      residualThreshold=1e-4, physicsClientId=client)
                    for j, q in zip(joints, qs):
                        p.setJointMotorControl2(robot, j, p.POSITION_CONTROL, targetPosition=float(q),
                                                force=250, physicsClientId=client)
                    p.stepSimulation(physicsClientId=client)
                    step_count += 1
                    for color, body in pads.items():
                        points = p.getContactPoints(bodyA=robot, bodyB=body, linkIndexA=ee, physicsClientId=client)
                        # Positive normal force means an actual force-bearing contact after this simulation step.
                        contacts = [pt for pt in points if pt[9] > 0]
                        touching = bool(contacts)
                        if touching and not was_touching[color]:
                            strongest = max(contacts, key=lambda point: point[9])
                            event = {'color': color, 'time_s': step_count / HZ,
                                     'robot_link': ee, 'pad_body': body,
                                     'position_on_pad': list(strongest[6]),
                                     'normal_force_n': float(strongest[9]),
                                     'strike': active['strike'] if active else None,
                                     'intended_color': active['color'] if active else None}
                            collisions.append(event)
                            glow_until[color] = step_count + round(0.25 * HZ)
                            if active is not None and active['color'] == color and not active['contact_confirmed']:
                                active.update(contact_confirmed=True, contact_time_s=step_count / HZ,
                                              contact_position_on_pad=event['position_on_pad'],
                                              normal_force_n=event['normal_force_n'])
                        was_touching[color] = touching

            move(home, 1.2)
            for index, strike in enumerate(strikes, 1):
                color = strike['color']
                x, y, z = PAD_POS[color]
                active = {'strike': index, 'color': color, 'pattern': strike['pattern'],
                          'start_time_s': step_count / HZ, 'contact_confirmed': False,
                          'contact_time_s': None, 'normal_force_n': None}
                events.append(active)
                above = [x, y, z + 0.25]
                move(above, 0.6)
                # The link frame is above the pad; collision geometry extends below it.
                move([x, y, z + 0.02], 0.35)
                move([x, y, z + 0.02], 0.15)
                move(above, 0.4)
                active['end_time_s'] = step_count / HZ
                active = None
            move(home, 0.6)
            writer.close()
            writer = None
            duration = frame_count / fps
            if frame_count * frame_steps != step_count:
                raise RuntimeError('Video and simulation duration diverged')
            synthesize([{'color': c['color'], 'contact_confirmed': True, 'contact_time_s': c['time_s']}
                        for c in collisions], duration, audio_path)
            cmd = [imageio_ffmpeg.get_ffmpeg_exe(), '-y', '-loglevel', 'error', '-i', silent,
                   '-i', str(audio_path), '-c:v', 'copy', '-c:a', 'aac', '-b:a', '192k',
                   '-movflags', '+faststart', '-shortest', str(output)]
            subprocess.run(cmd, check=True)
        result = {'video': str(output), 'audio': str(audio_path), 'fps': fps, 'width': width, 'height': height,
                  'duration_s': duration, 'simulation_hz': HZ, 'frame_count': frame_count,
                  'provenance': provenance, 'events': events, 'contacts': collisions,
                  'successful_strikes': sum(e['contact_confirmed'] for e in events),
                  'total_strikes': len(events),
                  'notes': ['A confirmed strike requires a positive PyBullet normal force between link 6 and the intended pad.',
                            'Pad illumination is a visual color change, not a simulated light source.',
                            'The audio is synthesized from each force-bearing contact onset, including unintended pads; it is not recorded sound.',
                            'All times are simulation seconds on the video timeline.']}
        log_path.write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding='utf-8')
        return result
    finally:
        if writer is not None:
            writer.close()
        p.disconnect(physicsClientId=client)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pattern', choices=['all', *PATTERNS], default='all')
    parser.add_argument('--plan', help='JSON file with a sequence; overrides --pattern')
    parser.add_argument('--output', default='output/robo_conductor.mp4')
    parser.add_argument('--log', default='output/results.json')
    parser.add_argument('--audio', default='output/contacts.wav')
    parser.add_argument('--fps', type=int, default=30)
    parser.add_argument('--width', type=int, default=960)
    parser.add_argument('--height', type=int, default=540)
    args = parser.parse_args()
    strikes, provenance = make_strikes(args.pattern, args.plan)
    result = run(strikes, provenance, args.output, args.log, args.audio, args.fps, args.width, args.height)
    print(f"Video: {result['video']} ({result['duration_s']:.2f} s); "
          f"confirmed strikes: {result['successful_strikes']}/{result['total_strikes']}; log: {args.log}")


if __name__ == '__main__':
    main()
